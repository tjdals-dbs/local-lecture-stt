import Darwin
import Foundation

/// Synthetic developer fixture for OS-enforced ancestor permissions. No GUI,
/// microphone, installed weights or user Application Support are accessed.
enum ModelSandboxProbe {
    static let marker = Data("T27 owned model sandbox fixture\n".utf8)
    static func execute(_ args: [String]) async throws {
        guard args.count == 2, ["seed", "import", "diagnostics", "symlink"].contains(args[0]) else {
            throw STTEngineError(.invalidInput)
        }
        let base = URL(fileURLWithPath: args[1], isDirectory: true)
        guard base.path.hasPrefix("/private/tmp/T27-Model-"),
              let resolved = realpath(base.path, nil) else { throw STTEngineError(.invalidInput) }
        defer { free(resolved) }
        guard String(cString: resolved) == base.path else { throw STTEngineError(.invalidInput) }
        let markerURL = base.appendingPathComponent(".fixture")
        if args[0] == "seed" {
            guard try FileManager.default.contentsOfDirectory(atPath: base.path).isEmpty else { throw STTEngineError(.invalidInput) }
            try marker.write(to: markerURL, options: .withoutOverwriting)
            for name in ["a", "b"] {
                let source = base.appendingPathComponent("opaque/source-" + name)
                try FileManager.default.createDirectory(at: source, withIntermediateDirectories: true)
                let bytes = Data("T27 SYNTHETIC MODEL \(name)".utf8)
                let descriptor = try ModelPackageDescriptor(engine: .init(id: .init("fixture"), version: "1"),
                    modelID: .init("fixture/" + name), revision: "1", format: "t27-fixture", variant: name,
                    quantization: "none", compute: "test", licenseIdentifier: "LicenseRef-Test",
                    licenseTextOrReference: "Generated synthetic data", licenseProvenance: "Generated by this fixture",
                    files: [.init(path: "weights.bin", byteCount: Int64(bytes.count), sha256: ModelPackageRules.sha256(bytes))])
                let manifest = try ModelInstallationManifest(descriptor: descriptor, origin: .suppliedLocal, installedAt: .init(Date()))
                try bytes.write(to: source.appendingPathComponent("weights.bin"), options: .withoutOverwriting)
                try JSONEncoder().encode(manifest).write(to: source.appendingPathComponent("manifest.json"), options: .withoutOverwriting)
            }
            return
        }
        guard try Data(contentsOf: markerURL) == marker else { throw STTEngineError(.invalidInput) }
        if args[0] == "diagnostics" {
            let log = LocalDiagnosticLog(directory: base.appendingPathComponent("opaque/diagnostics"))
            log.record(.init(source: .app, signal: .appStarted))
            let summary = try await log.summary()
            guard summary.fileCount == 1, summary.bytes > 0, summary.lastFailure == nil, summary.droppedEntries == 0 else {
                throw DiagnosticFailure.storage
            }
            print("diagnostics preserved and readable")
            return
        }
        let sources = ModelImportSources(), scopes = ProbeScopes()
        let repository = FileModelRepository(storeURL: { base.appendingPathComponent("opaque/Models") },
            sources: sources, validator: ProbeValidator(), references: ProbeReferences(),
            catalogLoader: .init(load: { try BundledModelCatalog(entries: []) }))
        let names = args[0] == "symlink" ? ["link/source-a"] : ["source-a", "source-b", "source-a"]
        for name in names {
            let source = base.appendingPathComponent("opaque/" + name)
            let id = await sources.register(source, start: { await scopes.start() }, stop: { await scopes.stop() })
            do {
                _ = try await repository.importPackage(from: id, descriptor: nil)
                await sources.unregister(id)
            } catch {
                await sources.unregister(id)
                if args[0] == "symlink" {
                    let counts = await scopes.counts()
                    guard counts == [1, 1], !FileManager.default.fileExists(atPath: base.appendingPathComponent("opaque/Models").path) else {
                        throw STTEngineError(.invalidResponse)
                    }
                    print("symlink refused; scope released; store untouched")
                    return
                }
                throw error
            }
        }
        guard args[0] != "symlink" else { throw STTEngineError(.invalidResponse) }
        let inventory = try await repository.inventory()
        let counts = await scopes.counts()
        guard inventory.count == 2, inventory.allSatisfy({ $0.state == .usable }), counts == [3, 3] else {
            throw STTEngineError(.invalidResponse)
        }
        print("two verified models; idempotent reimport; three scopes released")
    }
}

private actor ProbeScopes {
    var starts = 0, stops = 0
    func start() -> Bool { starts += 1; return true }
    func stop() { stops += 1 }
    func counts() -> [Int] { [starts, stops] }
}
private struct ProbeReferences: ModelReferenceChecking {
    func references(to descriptor: ModelPackageDescriptor) async -> ModelReferenceReport { .init(sessions: [], warnings: []) }
}
private struct ProbeValidator: OfflineModelFormatValidating {
    func validate(_ descriptor: ModelPackageDescriptor, directory: ModelPackageDirectory) async throws {
        guard descriptor.format == "t27-fixture", try directory.readMetadata("weights.bin").starts(with: Data("T27 SYNTHETIC MODEL".utf8)) else {
            throw ModelRepositoryCode.incompatible
        }
    }
}

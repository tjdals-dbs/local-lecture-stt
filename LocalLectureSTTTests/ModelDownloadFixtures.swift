final class DownloadProgressProbe: @unchecked Sendable {
    private let lock = NSLock()
    private var callback: (@Sendable (ModelTransferProgress) -> Void)?
    func record(_ callback: @escaping @Sendable (ModelTransferProgress) -> Void) { lock.withLock { self.callback = callback } }
    func emit(_ value: ModelTransferProgress) { let f = lock.withLock { callback }; f?(value) }
}
actor HeldDownloadTransport: ModelDownloadTransport {
    let entered = DownloadGate()
    let probe: DownloadProgressProbe
    private var preserving = false
    private(set) var closes = 0
    init(probe: DownloadProgressProbe) { self.probe = probe }
    func transfer(_ request: ModelTransferRequest, associated: @escaping @Sendable (String) async throws -> Void,
                  progress: @escaping @Sendable (ModelTransferProgress) -> Void) async -> ModelTransferOutcome {
        do { try await associated(request.association) }
        catch { return .init(receipt: nil, failure: .init(code: .journal), resumeData: nil, resumedOffset: 0) }
        probe.record(progress); await entered.hold()
        return .init(receipt: nil, failure: .init(code: .cancelled, transportCode: NSURLErrorCancelled),
                     resumeData: preserving ? Data("opaque-resume-token".utf8) : nil, resumedOffset: 0)
    }
    func discard(association: String) async throws { preserving = false; await entered.release() }
    func stop(preservingResume: Bool) async { preserving = preservingResume; await entered.release() }
    func close() async { closes += 1 }
}

actor DiscardTestTransport: ModelDownloadTransport {
    let gate = DownloadGate()
    let error: ModelDownloadFailure?
    private(set) var associations = [String]()
    private(set) var closes = 0
    init(error: ModelDownloadFailure? = nil) { self.error = error }
    func transfer(_ request: ModelTransferRequest, associated: @escaping @Sendable (String) async throws -> Void,
                  progress: @escaping @Sendable (ModelTransferProgress) -> Void) async -> ModelTransferOutcome {
        XCTFail("Discard must never start a transfer")
        return .init(receipt: nil, failure: .init(code: .transport), resumeData: nil, resumedOffset: 0)
    }
    func discard(association: String) async throws {
        associations.append(association); await gate.hold()
        if let error { throw error }
    }
    func stop(preservingResume: Bool) async {}
    func close() async { closes += 1 }
}

actor DownloadGate {
    let entered = XCTestExpectation(description: "acknowledged download gate")
    private var arrived = false
    private var released = false
    private var continuation: CheckedContinuation<Void, Never>?
    func hold() async {
        if arrived { return }; arrived = true; entered.fulfill()
        if !released { await withCheckedContinuation { continuation = $0 } }
    }
    func release() { released = true; continuation?.resume(); continuation = nil }
    func wait() async throws {
        guard await XCTWaiter.fulfillment(of: [entered], timeout: 10) == .completed else { release(); throw ModelDownloadFailure(code: .invalidState) }
    }
}

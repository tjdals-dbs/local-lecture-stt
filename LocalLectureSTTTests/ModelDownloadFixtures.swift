final class FixtureTransport: ModelDownloadTransport, @unchecked Sendable {
    let payloads: [String: Data]
    var error: ModelDownloadFailure?
    let closed = DownloadTestCounter()
    init(payloads: [String: Data], error: ModelDownloadFailure? = nil) { self.payloads = payloads; self.error = error }
    func transfer(_ request: ModelTransferRequest, associated: @escaping @Sendable (String) async throws -> Void,
                  progress: @escaping @Sendable (ModelTransferProgress) -> Void) async -> ModelTransferOutcome {
        do {
            try await associated(request.association)
            if let error { return .init(receipt: nil, failure: error, resumeData: nil, resumedOffset: 0) }
            let data = payloads[String(request.url.path.dropFirst())]!
            let url = URL(fileURLWithPath: "/private/tmp/stt-t13-receipt-" + UUID().uuidString)
            try data.write(to: url)
            defer { try? FileManager.default.removeItem(at: url) }
            let receipt = try ModelDownloadReceipt(temporaryURL: url)
            progress(.init(bytes: Int64(data.count), resumedOffset: 0))
            return .init(receipt: receipt, failure: nil, resumeData: nil, resumedOffset: 0)
        } catch { return .init(receipt: nil, failure: (error as? ModelDownloadFailure) ?? .init(code: .journal), resumeData: nil, resumedOffset: 0) }
    }
    func discard(association: String) async throws {}
    func stop(preservingResume: Bool) async {}
    func close() async { closed.increment() }
}

/// Actual TCP/HTTP fixture. Every worker is joined; stop releases held bodies and
/// shuts down open sockets on every exit. No sleeps, polling or internet requests.
final class DownloadHTTPServer: @unchecked Sendable {
    struct Request: Sendable { let path: String; let range: Int64? }
    private let listener: Int32
    let port: UInt16
    private let lock = NSLock()
    private let workers = DispatchGroup()
    private var stopped = false
    private var clients = Set<Int32>()
    private var records = [Request]()
    private let payloads: [String: Data]
    private let slow: Bool
    private let changedOnRange: Bool
    private let declaredExtraBytes: Int
    private let condition = NSCondition()
    private var released = false
    let prefixSent = XCTestExpectation(description: "HTTP fixture sent acknowledged prefix")
    var status: Int = 200
    var ignoreRange = false
    var redirect: String? = nil
    init(payloads: [String: Data], slow: Bool = false, status: Int = 200, ignoreRange: Bool = false, redirect: String? = nil, changedOnRange: Bool = false, declaredExtraBytes: Int = 0) throws {
        self.payloads = payloads; self.slow = slow; self.changedOnRange = changedOnRange; self.declaredExtraBytes = declaredExtraBytes; self.status = status; self.ignoreRange = ignoreRange; self.redirect = redirect
        let socketFD = socket(AF_INET, SOCK_STREAM, 0); listener = socketFD
        guard socketFD >= 0 else { throw ModelDownloadFailure(code: .transport) }
        var address = sockaddr_in(); address.sin_len = UInt8(MemoryLayout<sockaddr_in>.size); address.sin_family = sa_family_t(AF_INET)
        address.sin_addr.s_addr = inet_addr("127.0.0.1"); address.sin_port = 0
        let bound = withUnsafePointer(to: &address) { p in p.withMemoryRebound(to: sockaddr.self, capacity: 1) { bind(socketFD, $0, socklen_t(MemoryLayout<sockaddr_in>.size)) } }
        guard bound == 0, listen(socketFD, 16) == 0 else { Darwin.close(socketFD); throw ModelDownloadFailure(code: .transport) }
        var size = socklen_t(MemoryLayout<sockaddr_in>.size)
        _ = withUnsafeMutablePointer(to: &address) { p in p.withMemoryRebound(to: sockaddr.self, capacity: 1) { getsockname(socketFD, $0, &size) } }
        port = UInt16(bigEndian: address.sin_port)
        workers.enter()
        DispatchQueue.global().async { [self] in
            defer { workers.leave() }
            while true {
                let client = accept(listener, nil, nil)
                guard client >= 0 else { return }
                let accept = lock.withLock { () -> Bool in
                    if stopped { return false }; clients.insert(client); workers.enter(); return true
                }
                if !accept { Darwin.close(client); return }
                DispatchQueue.global().async { [self] in
                    defer { lock.withLock { _ = clients.remove(client) }; Darwin.close(client); workers.leave() }
                    serve(client)
                }
            }
        }
    }
    deinit { stop() }
    var requests: [Request] { lock.withLock { records } }
    func releaseBody() { condition.lock(); released = true; condition.broadcast(); condition.unlock() }
    func stop() {
        let first = lock.withLock { () -> Bool in
            if stopped { return false }; stopped = true
            for client in clients { _ = shutdown(client, SHUT_RDWR) }; return true
        }
        guard first else { return }
        releaseBody(); _ = shutdown(listener, SHUT_RDWR); Darwin.close(listener); workers.wait()
    }
    func configuration(progress: (@Sendable (ModelTransferProgress) -> Void)? = nil) -> ModelTransportConfiguration {
        .init(make: { _ in let c = URLSessionConfiguration.ephemeral; c.timeoutIntervalForRequest = 10; c.timeoutIntervalForResource = 20; return c },
              endpoint: { [port] url in URL(string: "http://127.0.0.1:\(port)" + url.path)! },
              permits: { [port] url in url.scheme == "http" && url.host == "127.0.0.1" && url.port == Int(port) })
    }
    private func send(_ data: Data, to client: Int32) -> Bool {
        data.withUnsafeBytes { raw in
            var offset = 0
            while offset < raw.count {
                let n = Darwin.send(client, raw.baseAddress!.advanced(by: offset), raw.count - offset, 0)
                if n <= 0 { return false }; offset += n
            }
            return true
        }
    }
    private func serve(_ client: Int32) {
        var yes: Int32 = 1; _ = setsockopt(client, SOL_SOCKET, SO_NOSIGPIPE, &yes, socklen_t(MemoryLayout<Int32>.size))
        var request = Data(); var buffer = [UInt8](repeating: 0, count: 4096)
        while request.range(of: Data("\r\n\r\n".utf8)) == nil {
            let n = recv(client, &buffer, buffer.count, 0); if n <= 0 { return }
            request.append(contentsOf: buffer.prefix(n)); if request.count > 16_384 { return }
        }
        let text = String(decoding: request, as: UTF8.self); let lines = text.components(separatedBy: "\r\n")
        let path = lines[0].split(separator: " ").dropFirst().first.map(String.init) ?? "/"
        let range = lines.first { $0.lowercased().hasPrefix("range: bytes=") }.flatMap { Int64($0.dropFirst(13).split(separator: "-").first ?? "") }
        lock.withLock { records.append(.init(path: path, range: range)) }
        if let redirect {
            _ = send(Data("HTTP/1.1 302 Found\r\nLocation: \(redirect)\r\nContent-Length: 0\r\nConnection: close\r\n\r\n".utf8), to: client); return
        }
        var data = payloads[String(path.dropFirst())] ?? Data("missing".utf8)
        if changedOnRange && range != nil && !data.isEmpty { data[0] ^= 1 }
        let start = ignoreRange ? 0 : Int(range ?? 0)
        guard start >= 0, start <= data.count else { return }
        let responseStatus = status != 200 ? status : start > 0 ? 206 : 200
        var headers = "HTTP/1.1 \(responseStatus) Fixture\r\nContent-Length: \(data.count - start + declaredExtraBytes)\r\nAccept-Ranges: bytes\r\nETag: \"fixture-v1\"\r\nLast-Modified: Wed, 21 Oct 2015 07:28:00 GMT\r\nConnection: close\r\n"
        if start > 0 { headers += "Content-Range: bytes \(start)-\(data.count - 1)/\(data.count)\r\n" }
        headers += "\r\n"
        guard send(Data(headers.utf8), to: client) else { return }
        if lines[0].hasPrefix("HEAD ") { return }
        if slow && start == 0 && data.count > 262_144 {
            guard send(data.subdata(in: 0..<262_144), to: client) else { return }
            prefixSent.fulfill()
            condition.lock(); while !released { condition.wait() }; condition.unlock()
            _ = send(data.subdata(in: 262_144..<data.count), to: client)
        } else { _ = send(data.subdata(in: start..<data.count), to: client) }
    }
}

